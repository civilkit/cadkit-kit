// @vitest-environment node
// Generates bosl/thumbs.generated.ts: a PNG (data URL) of every entry's default shape, built through the real kernel and rendered by
// @kit/snapshot. Run with BOSL_THUMBS=1 and CK_WASM set; otherwise this file only checks that the committed thumbnails cover every entry.
import { writeFileSync } from 'node:fs';
import { afterEach, describe, expect, it } from 'vitest';
import { Session } from '@ck/session';
import { emptyPart, type PartDoc } from '@ck/part-model';
import { createStore } from '@kit/store';
import { runScript, type ScriptHost } from '@kit/script';
import { snapshotOf } from '@kit/snapshot';
import { Controller } from '../controller';
import { BOSL_ENTRIES, boslEntry, defaultParams } from './bosl/entries';
import { buildBosl } from './bosl/build';
import { BOSL_THUMBS } from './bosl/thumbs.generated';

const sessions: Session[] = [];
afterEach(async () => { await Promise.all(sessions.splice(0).map((s) => s.close().catch(() => {}))); });

describe('parts library thumbnails', () => {
  it('the committed thumbnails cover every entry', () => {
    for (const e of BOSL_ENTRIES) expect(BOSL_THUMBS[e.id], e.id).toMatch(/^data:image\/png;base64,/);
    expect(Object.keys(BOSL_THUMBS).sort()).toEqual(BOSL_ENTRIES.map((e) => e.id).sort());
  });
  it.skipIf(!process.env.CK_WASM || !process.env.BOSL_THUMBS)('regenerates them', async () => {
    const out: Record<string, string> = {};
    for (const e of BOSL_ENTRIES) {
      const controller = new Controller({ store: createStore(), view: { setBody() {}, setHighlight() {}, setSketchEdit() {} }, kernel: { async open(d) { const s = await Session.open(d); sessions.push(s); return s; } } });
      const host: ScriptHost = {
        load: (d) => controller.load({ ...emptyPart('x'), ...d } as unknown as PartDoc),
        edit: (ops, why) => controller.edit(ops, why) as never,
        geometry: () => ({ mesh: controller.bodyFaces(), edges: controller.bodyEdges(), box: controller.bodyBox() }),
      };
      const sample = e.samples ? Object.values(e.samples)[0] : null;
      const ground = { plane: "'front'", ground: true, at: [0, 0] as [number, number], prefix: null };
      if (e.mask) {
        // a mask is drawn on its oracle host block
        const h = boslEntry(e.mask.host.entryId)!;
        expect((await runScript(h.script(e.mask.host.params, ground), host)).errors).toEqual([]);
        const sh = { load: async () => {}, edit: async () => ({ ok: true }), geometry: () => ({ mesh: null, edges: [], box: null }), build: (d: unknown, v: boolean) => controller.scratchBuild(d as never, v) as never, release: () => controller.scratchRelease(), facts: (n: never) => controller.scratchFacts(n) } as ScriptHost;
        const b = await buildBosl(sh, controller.document(), { entryId: e.id, params: defaultParams(e) }, { kind: 'face', face: 'F2.C1', planar: true, frame: { o: [0, 0, 20], x: [1, 0, 0], y: [0, 1, 0], z: [0, 0, 1] }, point: [0, 0, 20] }, false);
        if ('error' in b) throw new Error(b.error);
        expect((await controller.commit(b.ops)).ok).toBe(true);
      } else {
        const r = await runScript(e.script(sample && e.id !== 'cyl' ? sample : defaultParams(e), ground), host);
        expect(r.errors, e.id).toEqual([]);
      }
      const snap = await snapshotOf(sessions.at(-1)! as never, { view: 'iso', up: 'z', size: 96 });
      out[e.id] = 'data:image/png;base64,' + Buffer.from(snap.png).toString('base64');
    }
    const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
    writeFileSync(new URL('./bosl/thumbs.generated.ts', import.meta.url), `// Generated by \`BOSL_THUMBS=1 CK_WASM=... npx vitest run apps/cad/src/catalog/bosl.thumbs.kernel.test.ts\`: PNG data URLs of every entry's shape,\n// rendered by @kit/snapshot from the real kernel body (iso view, 96 px). Do not edit by hand.\nexport const BOSL_THUMBS: Record<string, string> = {\n${body}\n};\n`);
  }, 300000);
});
