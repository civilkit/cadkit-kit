// The pickleball example for the Script tab. docs/examples/pickleball.script.ts is the readable copy; a test keeps the two equal.
export const PICKLEBALL_SCRIPT: string = [
  "// Pickleball: hollow sphere, 74 mm outside diameter, 2 mm wall, 40 round 10 mm holes cut radially through the wall.",
  "// Paste into the Script tab and Run. Everything you would want to change is in the block below.",
  "// The pole axis is the Y axis. Each ring is [latitude in degrees (90 = +Y pole, 0 = equator, negative = south), holes in the ring].",
  "// Holes in a ring are evenly spaced; rings alternate by `stagger` (fraction of one step) so neighbouring rings do not line up.",
  "const { diameter, wall, holeD, stagger, margin } = variables({ diameter: 74, wall: 2, holeD: 10, stagger: 0.5, margin: 1.5 });",
  "const rings = [",
  "  [90, 1], [64, 5], [35, 8], [0, 12], [-35, 8], [-64, 5], [-90, 1],   // 2 + 10 + 16 + 12 = 40 holes",
  "];",
  "",
  "const R = diameter / 2, r = R - wall;",
  "const rad = Math.PI / 180;",
  "",
  "// hollow ball: revolve ADD of the outer half circle, revolve CUT of the inner one, both about the Y axis",
  "const ball = part('Pickleball')",
  "  .sketch('front', (s) => { s.arc([0, 0], [0, -R], [0, R]); s.line([0, R], [0, -R]); })",
  "  .revolve(360)",
  "  .sketch('front', (s) => { s.arc([0, 0], [0, -r], [0, r]); s.line([0, r], [0, -r]); })",
  "  .revolve(360, { op: 'cut' });",
  "",
  "// one radial hole per position: a plane tangent to the sphere `margin` mm outside it, a circle, a blind cut inward",
  "// far enough to clear the inner surface (the far wall is never touched)",
  "const dirs = [];",
  "rings.forEach(([lat, n], k) => {",
  "  for (let i = 0; i < n; i++) {",
  "    const az = ((i + (k % 2 ? stagger : 0)) / n) * 2 * Math.PI;",
  "    const c = Math.cos(lat * rad);",
  "    dirs.push([c * Math.cos(az), Math.sin(lat * rad), c * Math.sin(az)]);",
  "  }",
  "});",
  "// sanity: the holes must not overlap (centre-to-centre chord on the outer sphere vs hole diameter)",
  "let closest = Infinity;",
  "for (let i = 0; i < dirs.length; i++) for (let j = i + 1; j < dirs.length; j++) {",
  "  const d = 2 * R * Math.asin(Math.min(1, Math.hypot(dirs[i][0] - dirs[j][0], dirs[i][1] - dirs[j][1], dirs[i][2] - dirs[j][2]) / 2));",
  "  closest = Math.min(closest, d);",
  "}",
  "if (closest < holeD + 1) throw new Error(`holes too close: nearest centres ${closest.toFixed(1)} mm apart, hole diameter ${holeD}`);",
  "",
  "const depth = (R + margin) - (r - margin);",
  "dirs.forEach((n) => {",
  "  ball",
  "    .sketch(at({ origin: n.map((v) => v * (R + margin)), normal: n }), (s) => s.circle(holeD / 2))",
  "    .cut(depth);",
  "});",
].join('\n') + '\n';
