export const GLYPH_W = 5, GLYPH_H = 7, ADVANCE = 6, LINE = 9;

const GLYPHS = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(SRC)) {
  GLYPHS.set(ch, Uint8Array.from(rows.split(' ').map((r) => parseInt(r, 2))));
}

/** Rows (7 numbers of 5 bits) of a character. */
export function glyph(ch: string): Uint8Array {
  return GLYPHS.get(ch) ?? GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get('?')!;
}

export const textWidth = (s: string, scale = 1): number => (s.length ? (s.length * ADVANCE - 1) * scale : 0);
export const textHeight = (scale = 1): number => GLYPH_H * scale;
