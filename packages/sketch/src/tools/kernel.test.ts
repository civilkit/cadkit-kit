import { afterEach, describe, expect, it } from 'vitest';
import { Session } from '@ck/session';
import { emptyPart, type PartDoc } from '@ck/part-model';
import { toFeature, type SketchDraft } from '../index';
import { DEFAULT_SETTINGS, type Tool, type ToolEvent, type ToolOutput } from './types';
import { lineTool } from './line';
import { rectangleTool } from './rectangle';

const M = { shift: false, ctrl: false, alt: false };
const click = (x: number, y: number): ToolEvent => ({ type: 'click', at: { x, y }, mods: M });
const move = (x: number, y: number): ToolEvent => ({ type: 'move', at: { x, y }, mods: M });
const draft0 = (): SketchDraft => ({ id: 'F1', plane: { kind: 'std', id: 'front' }, points: [], entities: [], constraints: [], temp: [] });

function run<S>(tool: Tool<S>, events: ToolEvent[]): ToolOutput<S> {
  let out: ToolOutput<S> = { state: tool.start(), draft: draft0(), preview: [], fields: [] };
  for (const ev of events) out = tool.step(out.state, ev, out.draft, DEFAULT_SETTINGS);
  return out;
}

const sessions: Session[] = [];
afterEach(async () => { await Promise.all(sessions.splice(0).map((s) => s.close().catch(() => {}))); });

/** The drawn sketch plus an extrude, regenerated by the real kernel with the solver status switched on. */
async function build(draft: SketchDraft, depth = 5) {
  const doc = { ...emptyPart('Drawn'), features: [toFeature(draft), { type: 'extrude', op: 'add', sketch: 'F1', end: 'blind', depth, id: 'F2' }], seq: 3 } as unknown as PartDoc;
  const s = await Session.open(doc);
  sessions.push(s);
  return s.preview([], { sketchStatus: true });
}

describe('drawn sketches are valid for the real kernel', { skip: !process.env.CK_WASM }, () => {
  it('a rectangle with typed width and height extrudes to the typed volume', async () => {
    let o = run(rectangleTool, [click(0, 0), move(3, 2)]);
    o = rectangleTool.step(o.state, { type: 'field', id: 'w', value: 40, commit: true }, o.draft, DEFAULT_SETTINGS);
    o = rectangleTool.step(o.state, { type: 'field', id: 'h', value: 25, commit: true }, o.draft, DEFAULT_SETTINGS);
    const r = await build(o.draft, 5);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    const box = r.body!.box;
    expect(box.max[0] - box.min[0]).toBeCloseTo(40, 6);
    expect(box.max[1] - box.min[1]).toBeCloseTo(25, 6);
    expect(r.body!.sketches[0].status).toMatchObject({ state: 'under', dof: 2 }); // size is fixed, position is free
  });

  it('a closed chain of lines with inferred H and V makes a solid', async () => {
    const o = run(lineTool, [
      click(0, 0), move(30, 0.2), click(30, 0.2), move(30.1, 20), click(30.1, 20), move(0, 20.1), click(0, 20.1),
      { type: 'move', at: { x: 0, y: 0 }, snap: { kind: 'point', at: { x: 0, y: 0 }, pointId: 'p1' }, mods: M },
      { type: 'click', at: { x: 0, y: 0 }, snap: { kind: 'point', at: { x: 0, y: 0 }, pointId: 'p1' }, mods: M },
    ]);
    const r = await build(o.draft, 4);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    const box = r.body!.box;
    expect(box.max[0] - box.min[0]).toBeCloseTo(30, 6);
    expect(box.max[1] - box.min[1]).toBeCloseTo(20, 6);
    expect(r.body!.sketches[0].status?.conflicts).toEqual([]);
  });
});
