import { afterEach, describe, expect, it } from 'vitest';
import { Session } from '@ck/session';
import { emptyPart, type PartDoc } from '@ck/part-model';
import { toFeature, type SketchDraft } from '../index';
import { DEFAULT_SETTINGS, type Tool, type ToolEvent, type ToolOutput } from './types';
import { centerRectangleTool } from './center-rectangle';
import { pointTool } from './point';
import { centerlineTool } from './centerline';
import { ellipseTool } from './ellipse';
import { polygonTool } from './polygon';
import { slotTool } from './slot';

const M = { shift: false, ctrl: false, alt: false };
const click = (x: number, y: number): ToolEvent => ({ type: 'click', at: { x, y }, mods: M });
const move = (x: number, y: number): ToolEvent => ({ type: 'move', at: { x, y }, mods: M });
const field = (id: string, value: number): ToolEvent => ({ type: 'field', id, value, commit: true });
const key = (k: string): ToolEvent => ({ type: 'key', key: k });
const draft0 = (): SketchDraft => ({ id: 'F1', plane: { kind: 'std', id: 'front' }, points: [], entities: [], constraints: [], temp: [] });

function run<S>(tool: Tool<S>, events: ToolEvent[], draft = draft0()): ToolOutput<S> {
  let out: ToolOutput<S> = { state: tool.start(), draft, preview: [], fields: [] };
  for (const ev of events) out = tool.step(out.state, ev, out.draft, DEFAULT_SETTINGS);
  return out;
}

const sessions: Session[] = [];
afterEach(async () => { await Promise.all(sessions.splice(0).map((s) => s.close().catch(() => {}))); });

/** The drawn sketch plus an extrude, regenerated by the real kernel; returns the preview, the solid facts and the solver status. */
async function build(draft: SketchDraft, depth = 5) {
  const doc = { ...emptyPart('Drawn'), features: [toFeature(draft), { type: 'extrude', op: 'add', sketch: 'F1', end: 'blind', depth, id: 'F2' }], seq: 3 } as unknown as PartDoc;
  const s = await Session.open(doc);
  sessions.push(s);
  const r = await s.preview([], { sketchStatus: true });
  const facts = await s.facts();
  return { r, facts, status: r.body?.sketches[0].status };
}
const size = (b: { min: number[]; max: number[] }) => [b.max[0] - b.min[0], b.max[1] - b.min[1], b.max[2] - b.min[2]];

describe('shape tools draw sketches the real kernel accepts', { skip: !process.env.CK_WASM }, () => {
  it('centre rectangle: typed sizes extrude to the typed box, centred on the centre', async () => {
    const o = run(centerRectangleTool, [click(10, 20), move(11, 21), field('w', 40), field('h', 30)]);
    const { r, facts, status } = await build(o.draft, 5);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    const box = r.body!.box;
    expect(size(box)[0]).toBeCloseTo(40, 6);
    expect(size(box)[1]).toBeCloseTo(30, 6);
    expect((box.min[0] + box.max[0]) / 2).toBeCloseTo(10, 6);
    expect(facts.volume).toBeCloseTo(40 * 30 * 5, 4);
    expect(facts.solids).toBe(1);
    expect(status?.conflicts).toEqual([]);
  });

  it('point and centreline entities beside a profile do not break it, and the centreline is construction', async () => {
    const rect = run(centerRectangleTool, [click(0, 0), click(10, 5)]).draft;
    const withLine = run(centerlineTool, [click(-12, 0), click(12, 0)], rect).draft;
    const draft = run(pointTool, [click(2, 2)], withLine).draft;
    expect(draft.entities.find((e) => e.construction)).toBeDefined();
    const { r, facts, status } = await build(draft, 3);
    expect(r.ok).toBe(true);
    expect(size(r.body!.box)[0]).toBeCloseTo(20, 6);       // the centreline (24 long) is not part of the solid
    expect(facts.volume).toBeCloseTo(20 * 10 * 3, 4);
    expect(status?.conflicts).toEqual([]);
  });

  // Box extents of curved edges come from the tessellated mesh, so they get a looser tolerance than volumes.
  it('ellipse: p is the semi-major axis end and r the semi-minor, volume is pi a b depth', async () => {
    const o = run(ellipseTool, [click(5, 5), click(15, 5), click(5, 9)]);       // a = 10 along x, b = 4
    const { r, facts, status } = await build(o.draft, 3);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    const box = r.body!.box;
    expect(size(box)[0]).toBeCloseTo(20, 2);
    expect(size(box)[1]).toBeCloseTo(8, 2);
    expect((box.min[0] + box.max[0]) / 2).toBeCloseTo(5, 2);
    expect(facts.volume).toBeCloseTo(Math.PI * 10 * 4 * 3, 2);
    expect(status?.conflicts).toEqual([]);
  });

  it('ellipse with the axis along y: r is measured perpendicular to the axis, not along x', async () => {
    const o = run(ellipseTool, [click(0, 0), click(0, 6), click(2, 0)]);        // a = 6 along y, b = 2
    const { r, status } = await build(o.draft, 2);
    expect(r.ok).toBe(true);
    expect(size(r.body!.box)[0]).toBeCloseTo(4, 2);
    expect(size(r.body!.box)[1]).toBeCloseTo(12, 2);
    expect(status?.conflicts).toEqual([]);
  });

  it('ellipse with typed major length and minor radius keeps its size under the solver', async () => {
    let o = run(ellipseTool, [click(0, 0), move(7, 1), field('len', 12), field('ang', 0)]);
    o = { ...o, ...ellipseTool.step(o.state, field('r', 5), o.draft, DEFAULT_SETTINGS) };
    const { r, facts, status } = await build(o.draft, 1);
    expect(r.ok).toBe(true);
    expect(size(r.body!.box)[0]).toBeCloseTo(24, 2);
    expect(size(r.body!.box)[1]).toBeCloseTo(10, 2);
    expect(facts.volume).toBeCloseTo(Math.PI * 12 * 5, 2);
    expect(status?.conflicts).toEqual([]);
  });

  it('inscribed hexagon: closed profile, solver keeps the radius, volume matches', async () => {
    const o = run(polygonTool, [click(0, 0), move(3, 0), field('r', 10), field('ang', 0)]);
    const { r, facts, status } = await build(o.draft, 4);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    expect(size(r.body!.box)[0]).toBeCloseTo(20, 5);                 // vertex to vertex
    expect(size(r.body!.box)[1]).toBeCloseTo(2 * 10 * Math.sin(Math.PI / 3), 5);
    expect(facts.volume).toBeCloseTo((3 * Math.sqrt(3) / 2) * 100 * 4, 3);
    expect(facts.solids).toBe(1);
    expect(status?.conflicts).toEqual([]);
  });

  it('circumscribed pentagon and a triangle are valid solids', async () => {
    const pent = run(polygonTool, [key('m'), key('-'), click(0, 0), click(5, 0)]);          // 5 sides, apothem 5
    expect(pent.draft.entities).toHaveLength(5);
    const a = await build(pent.draft, 2);
    expect(a.r.ok).toBe(true);
    expect(a.facts.volume).toBeCloseTo(5 * 25 * Math.tan(Math.PI / 5) * 2, 3);              // area = n a^2 tan(pi/n)
    expect(a.status?.conflicts).toEqual([]);
    const tri = run(polygonTool, [{ type: 'field', id: 'sides', value: 3 }, click(0, 0), click(0, 10)]);
    const b = await build(tri.draft, 1);
    expect(b.r.ok).toBe(true);
    expect(b.facts.volume).toBeCloseTo((Math.sqrt(3) / 4) * (10 * Math.sqrt(3)) ** 2, 3);
    expect(b.status?.conflicts).toEqual([]);
  });

  it('horizontal slot: arcs counter-clockwise p1 -> p2 give box (L + w) x w and area L w + pi (w/2)^2', async () => {
    const o = run(slotTool, [click(0, 0), click(20, 0), click(20, 4)]);            // L 20, w 8
    const { r, facts, status } = await build(o.draft, 3);
    expect(r.errors).toEqual([]);
    expect(r.ok).toBe(true);
    const box = r.body!.box;
    expect(size(box)[0]).toBeCloseTo(28, 1);
    expect(size(box)[1]).toBeCloseTo(8, 5);
    expect(box.min[0]).toBeCloseTo(-4, 1);
    expect(box.max[0]).toBeCloseTo(24, 1);
    expect(facts.volume).toBeCloseTo((20 * 8 + Math.PI * 16) * 3, 3);
    expect(facts.solids).toBe(1);
    expect(status?.conflicts).toEqual([]);
  });

  it('slot in any direction, drawn from the right to the left and from a tilted axis', async () => {
    const left = run(slotTool, [click(0, 0), click(-20, 0), click(-20, 4)]);
    const a = await build(left.draft, 3);
    expect(a.r.ok).toBe(true);
    expect(size(a.r.body!.box)[0]).toBeCloseTo(28, 1);
    expect(a.facts.volume).toBeCloseTo((20 * 8 + Math.PI * 16) * 3, 3);
    const tilted = run(slotTool, [click(0, 0), click(12, 16), click(-3, 4)]);       // L 20, pointer 4.8 from the axis: width 9.6
    const b = await build(tilted.draft, 1);
    expect(b.r.ok).toBe(true);
    expect(b.facts.volume).toBeCloseTo(20 * 9.6 + Math.PI * 4.8 ** 2, 3);
    expect(b.status?.conflicts).toEqual([]);
  });

  it('slot with typed length, angle and width holds those dimensions', async () => {
    let o = run(slotTool, [click(0, 0), move(5, 1), field('len', 30), field('ang', 90)]);
    o = { ...o, ...slotTool.step(o.state, field('w', 6), o.draft, DEFAULT_SETTINGS) };
    const { r, facts, status } = await build(o.draft, 2);
    expect(r.ok).toBe(true);
    expect(size(r.body!.box)[0]).toBeCloseTo(6, 5);
    expect(size(r.body!.box)[1]).toBeCloseTo(36, 1);
    expect(facts.volume).toBeCloseTo((30 * 6 + Math.PI * 9) * 2, 3);
    expect(status?.conflicts).toEqual([]);
  });
});
