#!/usr/bin/env node
// Dev-time: build the Material editor's steel grades (apps/cad/src/materials.steel.json) from the verified material record
// apps/cad/src/frame/data/steel-materials.json. The output is committed; re-run after the data changes:
//   node tools/build_steel_materials.mjs        (--check: only compare, for tests)
// Units: the record is in MPa and kg/m3; the catalogue (materials.ts) keeps GPa for moduli, MPa for strengths and 1e-6/K for expansion.
// `verified` is the record's flag (true: the headline strengths agree across two independent public sources or a mill catalogue that
// reproduces the standard table); the editor shows an "unverified" badge when it is false.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const CHECK = process.argv.includes('--check');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'apps/cad/src/frame/data/steel-materials.json'), 'utf8'));
const out = join(root, 'apps/cad/src/materials.steel.json');

/** id of the record -> the name a part file stores (`doc.material`), the product standard as the bill of materials prints it, the grade, a swatch colour. */
const NAMES = {
  'EN-10025-2-S235': ['EN 10025-2 S235', 'EN 10025-2', 'S235', '#8f99a6'],
  'EN-10025-2-S275': ['EN 10025-2 S275', 'EN 10025-2', 'S275', '#8c96a4'],
  'EN-10025-2-S355': ['EN 10025-2 S355', 'EN 10025-2', 'S355', '#8993a2'],
  'EN-10210-S355J2H': ['EN 10210 S355J2H', 'EN 10210', 'S355J2H', '#8690a0'],
  'EN-10219-S355J2H': ['EN 10219 S355J2H', 'EN 10219', 'S355J2H', '#8690a0'],
  'ASTM-A36': ['ASTM A36', 'ASTM A36', '36', '#929ba8'],
  'ASTM-A992': ['ASTM A992', 'ASTM A992', '50', '#8d97a5'],
  'ASTM-A572-Gr50': ['ASTM A572 Gr 50', 'ASTM A572', 'Gr 50', '#8b95a3'],
  'ASTM-A53-GrB': ['ASTM A53 Gr B', 'ASTM A53', 'Gr B', '#939ca9'],
  'ASTM-A500-GrB-round': ['ASTM A500 Gr B round', 'ASTM A500', 'Gr B', '#9099a6'],
  'ASTM-A500-GrB-shaped': ['ASTM A500 Gr B shaped', 'ASTM A500', 'Gr B', '#8e98a5'],
  'ASTM-A500-GrC-round': ['ASTM A500 Gr C round', 'ASTM A500', 'Gr C', '#8c96a3'],
  'ASTM-A500-GrC-shaped': ['ASTM A500 Gr C shaped', 'ASTM A500', 'Gr C', '#8a94a2'],
  'AS-NZS-3679.1-300': ['AS/NZS 3679.1 300', 'AS/NZS 3679.1', '300', '#939daa'],
  'AS-NZS-3679.1-350': ['AS/NZS 3679.1 350', 'AS/NZS 3679.1', '350', '#8f99a7'],
};
const r3 = (v) => Math.round(v * 1000) / 1000;
const mats = src.materials.map((m) => {
  const n = NAMES[m.id];
  if (!n) throw new Error('no name for material ' + m.id);
  return {
    id: m.id.toLowerCase(), name: n[0], region: m.region, standard: n[1], grade: n[2], density: m.density_kg_m3, color: n[3],
    youngs: r3(m.E_MPa / 1000), shear: r3(m.G_MPa / 1000), poisson: m.poisson, yield: m.fy_MPa, ultimate: m.fu_MPa,
    ...(m.thermal_expansion_per_C ? { expansion: r3(m.thermal_expansion_per_C * 1e6) } : {}),
    ...(m.fy_alt_A500_21_MPa ? { yieldAlt: m.fy_alt_A500_21_MPa } : {}),
    verified: m.provenance.verified === true,
    note: m.thickness_note,
  };
});
if (new Set(mats.map((m) => m.id)).size !== mats.length) throw new Error('duplicate material id');
const text = '{\n "note": "Generated by tools/build_steel_materials.mjs from frame/data/steel-materials.json: do not edit. Verified steel grades for the Material editor (MPa, GPa, 1e-6/K, kg/m3).",\n "materials": [\n' + mats.map((m) => '  ' + JSON.stringify(m)).join(',\n') + '\n ]\n}\n';
if (CHECK) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error('materials.steel.json is not what the data builds: run node tools/build_steel_materials.mjs'); process.exitCode = 1; }
} else writeFileSync(out, text);
console.log('materials.steel.json', mats.length, 'materials', text.length, 'bytes');
