// ================================================================ shared: hardware and materials for the US and EU libraries
// Hardware (gussets, brackets, plugs, feet) is offered on hollow sections up to the size a frame is built from (the shipped US limit: rectangular
// up to 8 in = 203.2 mm, round up to 8.625 in = 219.1 mm outside). Larger hollow sections and every open section list none.
const framed = (r) => (r.kind === 'CHS' ? r.d <= 222.25 : Math.max(r.d, r.b) <= 203.2 + 0.01);
function hollowOf(kind, d, b, t, ro) {
  // kind CHS (d = outside diameter), SHS or RHS (d = depth, b = width); `ro` outside corner radius
  if (kind === 'CHS') {
    const dd = num(d);
    return { family: 'chs', section: { kind: 'roundTube', d: round(d, 3), t: round(t, 3) }, tube: { min: d, inner: d - 2 * t, cap: () => capFor(`plug-rd-${dd}`, `round ${dd}, 3 thick`) } };
  }
  const sq = kind === 'SHS', min = Math.min(d, b);
  return { family: sq ? 'shs' : 'rhs', section: { kind: 'rectTube', w: round(b, 3), h: round(d, 3), t: round(t, 3), r: round(ro, 3) },
    tube: { min, inner: min - 2 * t, cap: () => capFor(sq ? `plug-sq-${num(d)}` : `plug-rect-${num(d)}x${num(b)}`, sq ? `square ${num(d)}, 3 thick` : `rectangular ${num(d)} x ${num(b)}, 3 thick`) } };
}
const withHardware = (h, inFrame) => { const { tube, ...rest } = h; return inFrame ? { ...rest, hardware: tubeHardware(tube.min, tube.inner, tube.cap()) } : rest; };
/** Fractions as AISC writes them: "3/4", "2-1/2", "0.500". */
function frac(s) {
  const m = /^(\d+)-(\d+)\/(\d+)$/.exec(s), f = /^(\d+)\/(\d+)$/.exec(s);
  if (m) return +m[1] + +m[2] / +m[3];
  if (f) return +f[1] / +f[2];
  if (!/^\d+(\.\d+)?$/.test(s)) throw new Error('bad size ' + s);
  return +s;
}

// ================================================================ United States
const us = [];
const usData = read('us-sections.json');
const AISC_SRC = cite('aisc', 'AISC Shapes Database, Version 15.0 (November 2017; Steel Construction Manual, 15th edition)', { note: 'Spreadsheet taken from a public redistribution unchanged (aisc.org refused the download); inches and lb/ft converted exactly to millimetres and kilograms per metre. Reuse terms not reviewed.' });
// default material of each family (a choice by common AISC practice, not from a primary source: flagged `material_default`, to confirm)
const US_MAT = { W: 'ASTM-A992', S: 'ASTM-A36', C: 'ASTM-A36', MC: 'ASTM-A36', L: 'ASTM-A36', SHS: 'ASTM-A500-GrC-shaped', RHS: 'ASTM-A500-GrC-shaped', CHS: 'ASTM-A500-GrC-round', PIPE: 'ASTM-A53-GrB' };
const mats = Object.fromEntries(read('steel-materials.json').materials.map((m) => [m.id, m]));
const usStd = { 'ASTM-A992': ['ASTM A992', '50'], 'ASTM-A36': ['ASTM A36', '36'], 'ASTM-A500-GrC-shaped': ['ASTM A500', 'Gr C'], 'ASTM-A500-GrC-round': ['ASTM A500', 'Gr C'], 'ASTM-A53-GrB': ['ASTM A53', 'Gr B'] };
const lc = (s) => s.replace(/X/g, 'x');
for (const r of usData.sections) {
  const g = r.geometry_mm, ref = US_MAT[r.form], [standard, grade] = usStd[ref];
  if (!mats[ref]) throw new Error('unknown material ' + ref);
  const imp = r.designation_imperial;
  const base = { corner: 'butt', region: 'US', standard, grade, material_ref: ref.toLowerCase(), material_default: true, designation: imp, designation_metric: r.designation, mass_per_m_kg: round(r.mass_per_m_kg, 3),
    source: { ref: AISC_SRC, table: `Database v15.0, ${r.form === 'PIPE' ? 'pipe' : r.form === 'L' ? 'angle' : r.form} rows`, verified: r.provenance.verified === true } };
  const key = imp.toLowerCase().replace(/\//g, '-');
  if (r.form === 'W' || r.form === 'S') {
    // W: flange/web/fillet from the database; S has sloped flanges, drawn with the mean flange thickness and no root fillet (mass within 3 %)
    us.push({ id: `us-${key}`, label: `${lc(imp)} (${lc(r.designation)})`, family: r.form.toLowerCase(), ...base,
      section: { kind: 'ibeam', w: g.bf, h: g.d, tf: g.tf, tw: g.tw, ...(g.r ? { r: g.r } : {}) } });
  } else if (r.form === 'C' || r.form === 'MC') {
    us.push({ id: `us-${key}`, label: `${lc(imp)} (${lc(r.designation)})`, family: r.form.toLowerCase(), ...base, section: { kind: 'channel', w: g.bf, h: g.d, tf: g.tf, tw: g.tw } });
  } else if (r.form === 'L') {
    us.push({ id: `us-${key}`, label: `${lc(imp)} (${lc(r.designation)})`, family: 'angle', ...base, corner: 'mitre', section: { kind: 'angle', w: g.leg_short, h: g.leg_long, t: g.t } });
  } else if (r.form === 'PIPE') {
    const h = hollowOf('CHS', g.od, 0, g.t_nom, 0);
    us.push({ id: `us-${key}`, label: `Pipe ${imp.replace(/^Pipe/, '').replace(/(STD|XXS|XS)$/, ' $1')} (DN${r.designation.replace(/^Pipe(\d+).*/, '$1')})`, ...withHardware(h, framed({ kind: 'CHS', d: g.od })), ...base, family: 'pipe', corner: 'mitre' });
  } else {
    // HSS: ids are the ones the first US release used (inch sizes and nominal wall); geometry on the nominal wall with 2 t corners (area then agrees with the
    // catalogue mass within 0.5 %); the AISC tabulated section properties use the design wall (0.93 t), see the guide
    const parts = imp.replace(/^HSS/, '').split('X').map(frac);
    const metric = r.designation.replace(/^HSS/, '').replace(/X/g, ' x ');
    let id, h;
    // sizes come from the designation in inches (exact), not from the database's rounded millimetre columns
    if (r.form === 'CHS') { id = `us-hss-${parts[0]}x${parts[1].toFixed(3)}`; h = hollowOf('CHS', parts[0] * IN, 0, parts[1] * IN, 0); }
    else { id = `us-hss-${parts[0]}x${parts[1]}x${parts[2].toFixed(3)}`; h = hollowOf(r.form, parts[0] * IN, parts[1] * IN, parts[2] * IN, 2 * parts[2] * IN); }
    const inFrame = framed(r.form === 'CHS' ? { kind: 'CHS', d: g.od } : { kind: r.form, d: g.d, b: g.b });
    us.push({ id, label: `HSS ${lc(imp.slice(3))} (${metric} mm)`, ...withHardware(h, inFrame), ...base, corner: 'mitre' });
  }
}
const FAM_US = ['w', 's', 'c', 'mc', 'angle', 'shs', 'rhs', 'chs', 'pipe'];
const sortBy = (fam) => (a, b) => fam.indexOf(a.family) - fam.indexOf(b.family) || size(a) - size(b) || (a.section.w ?? 0) - (b.section.w ?? 0) || a.mass_per_m_kg - b.mass_per_m_kg || a.id.localeCompare(b.id);
us.sort(sortBy(FAM_US));

