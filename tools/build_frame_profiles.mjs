// committed; re-run after the data changes:  node tools/build_frame_profiles.mjs   (--check: only compare, for tests)
// Sources (see the data files and guide "Frame stock data sources"): rolled sections au-sections.json / au-sections-i.json (InfraBuild
// catalogue, re-checked by tools/verify_au_sources.mjs), hollow sections au-hollow-atm.json (tools/extract_atm_hollow.mjs), US HSS
