const read = (f) => JSON.parse(readFileSync(join(dir, 'data', f), 'utf8'));
const round = (v, n = 3) => Math.round(v * 10 ** n) / 10 ** n;
const num = (v) => String(round(v, 3));
const IN = 25.4, LBFT = 0.45359237 / 0.3048;   // mm per inch, kg/m per lb/ft (exact)
const sources = {};   // short key -> full citation, written once per file (a profile points at it with `source.ref`)
const cite = (ref, document, extra = {}) => { sources[ref] = { document, ...extra }; return ref; };

// ---- hardware offered on closed sections (open sections and bars: none, see the guide), by the smallest outside dimension
const fittings = {};
function capFor(id, spec) {
  fittings[id] ??= { label: 'Tube plug, ' + spec.split(',')[0], kind: 'cap', spec, part: { kind: 'cap', t: 3 } };
  return id;
}
function tubeHardware(min, innerMin, capId) {
  const joint = [min < 45 ? 'gusset-3' : 'gusset-5'];
  if (min >= 25 && min < 40) joint.push('bracket-tube-25');
  else if (min >= 40 && min < 50) joint.push('bracket-tube-40');
  else if (min >= 50 && min < 100) joint.push('bracket-tube-50');
  const hw = { joint, cap: [capId] };
  if (innerMin >= 15) hw.foot = ['foot-steel'];
  return hw;
}

function hollow(r, region, standard, source) {
  const out = {};
  if (r.kind === 'CHS') {
    const dd = num(r.d);
    out.family = 'chs'; out.section = { kind: 'roundTube', d: r.d, t: r.t };
    out.hardware = tubeHardware(r.d, r.d - 2 * r.t, capFor(`plug-rd-${dd}`, `round ${dd}, 3 thick`));
  } else {
    const sq = r.kind === 'SHS';
    const t = r.t, ro = t <= 3 ? 2 * t : 2.5 * t;      // outside corner radius (AS/NZS 1163 sections: 2 t up to 3 mm, else 2.5 t)
    out.family = sq ? 'shs' : 'rhs'; out.section = { kind: 'rectTube', w: r.b, h: r.d, t, r: round(ro, 3) };
    out.hardware = tubeHardware(Math.min(r.b, r.d), Math.min(r.b, r.d) - 2 * t, capFor(sq ? `plug-sq-${num(r.d)}` : `plug-rect-${num(r.d)}x${num(r.b)}`, sq ? `square ${num(r.d)}, 3 thick` : `rectangular ${num(r.d)} x ${num(r.b)}, 3 thick`));
  }
  return out;
}

