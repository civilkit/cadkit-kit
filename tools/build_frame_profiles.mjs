// ---------------------------------------------------------------- write: one profile per line, fittings sorted
function write(file, note, profiles) {
  const used = new Set(profiles.flatMap((p) => Object.values(p.hardware ?? {}).flat()));
  const fit = Object.fromEntries(Object.entries(fittings).filter(([id]) => used.has(id)).sort(([a], [b]) => a.localeCompare(b)));
  const ids = new Set();
  for (const p of profiles) { if (ids.has(p.id)) throw new Error('duplicate id ' + p.id); ids.add(p.id); }
  const refs = [...new Set(profiles.map((p) => p.source.ref))].sort();
  const text = '{\n "version": 1,\n "note": ' + JSON.stringify(note) + ',\n "defaults": {"material": "mild-steel", "fittings": [{"id": "weld", "per": "joint", "qty": 1}]},\n "sources": {\n' + refs.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(sources[k])}`).join(',\n') + '\n },\n "fittings": {\n' + Object.entries(fit).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n') + '\n },\n "profiles": [\n' + profiles.map((p) => '  ' + JSON.stringify(p)).join(',\n') + '\n ]\n}\n';
  if (CHECK) {
    const same = existsSync(join(dir, file)) && readFileSync(join(dir, file), 'utf8') === text;
    if (!same) { console.error(file + ' is not what the data builds: run node tools/build_frame_profiles.mjs'); process.exitCode = 1; }
  } else writeFileSync(join(dir, file), text);
  const n = {}; for (const p of profiles) n[p.family] = (n[p.family] ?? 0) + 1;
  console.log(file, profiles.length, JSON.stringify(n), text.length, 'bytes');
}
write('profiles.au.json', 'Generated by tools/build_frame_profiles.mjs from the data in ./data: do not edit. Australian steel stock: AS/NZS 1163 hollow sections (Australian Tube Mills tables) and AS/NZS 3679.1 rolled sections and bars (InfraBuild catalogue). mass_per_m_kg is the catalogue mass; each profile names its source table and whether the row was checked against the published text.', au);
write('profiles.us.json', 'Generated by tools/build_frame_profiles.mjs from the data in ./data: do not edit. US steel: AISC Shapes Database W, S, C, MC and L shapes, hollow structural sections (HSS, ASTM A500) and pipe (ASTM A53). Sizes in millimetres, mass_per_m_kg is the catalogue weight (nominal wall for HSS and pipe). material_ref is the default grade of the family (to confirm).', us);
write('profiles.eu.json', 'Generated by tools/build_frame_profiles.mjs from the data in ./data: do not edit. European steel: IPE, IPE A/O/AA, HE A/B/M/AA, IPN and UPN sections (ArcelorMittal catalogue) and EN 10210 hot-finished and EN 10219 cold-formed hollow sections (SCI P363). mass_per_m_kg is the catalogue mass. material_ref is the default grade of the family (to confirm).', eu);
