#!/usr/bin/env node
// Regenerates packages/fcstd/corpus/COVERAGE.md from the model headers, the dumps and generated/STATUS.json.
//   node tools/fcstd-corpus/coverage.mjs [--other DIR_OF_OTHER_VERSION]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const corpus = path.resolve(here, '../../packages/fcstd/corpus')
const gen = path.join(corpus, 'generated')
const args = process.argv.slice(2)
const other = args.includes('--other') ? args[args.indexOf('--other') + 1] : ''
const models = fs.readdirSync(path.join(corpus, 'models')).filter(f => /^\d\d_.*\.py$/.test(f)).sort()
const status = JSON.parse(fs.readFileSync(path.join(gen, 'STATUS.json'), 'utf8'))
const status2 = other && fs.existsSync(path.join(other, 'STATUS.json')) ? JSON.parse(fs.readFileSync(path.join(other, 'STATUS.json'), 'utf8')) : null
const v1 = JSON.parse(fs.readFileSync(path.join(gen, models[0].replace('.py', '.dump.json')), 'utf8')).freecad.version
const v2 = other ? JSON.parse(fs.readFileSync(path.join(other, models[0].replace('.py', '.dump.json')), 'utf8')).freecad.version : ''
const skip = new Set(['App::Origin', 'App::Line', 'App::Plane', 'App::Point', 'Spreadsheet::Sheet', 'App::VarSet'])
const group = n => { const k = Number(n.slice(0, 2)); return k < 20 ? 'Sketches (10-19)' : k < 60 ? 'Part Design (20-59)' : k < 70 ? 'Part workbench (60-69)' : k < 80 ? 'Structure (70-79)' : 'Configuration and expressions (80-89)' }
const ok = s => (s ? (s.ok && (!s.variant || s.variant.ok) ? 'ok' : 'FAILED: ' + (s.error ?? s.variant?.error ?? '').slice(0, 120)) : 'not run')

let md = `# Corpus coverage\n\nGenerated by \`tools/fcstd-corpus/coverage.mjs\`. Per model: what it covers and the analytic expectations (from the header comment of the script),\nthe FreeCAD feature types it creates (read from the dump), and the result with FreeCAD ${v1}${other ? ` and ${v2}` : ''}.\n"V" = the model has a parameter variant (\`.v1\` files). Closed-form numbers in the headers were compared with FreeCAD's measures in the dumps while the models were written (a mismatch was a bug in the header or the model); where a header says "value from FreeCAD" there is no closed form.\n\n`
let cur = ''
let nvar = 0
for (const f of models) {
  const name = f.slice(0, -3)
  const src = fs.readFileSync(path.join(corpus, 'models', f), 'utf8').split('\n')
  const head = []
  for (const l of src) { if (l.startsWith('#')) head.push(l.replace(/^#\s?/, '')); else break }
  const hasVar = /^def variant/m.test(src.join('\n'))
  if (hasVar) nvar++
  const dumpPath = path.join(gen, name + '.dump.json')
  let types = []
  if (fs.existsSync(dumpPath)) {
    const d = JSON.parse(fs.readFileSync(dumpPath, 'utf8'))
    types = [...new Set(d.objects.map(o => o.typeId).filter(t => !skip.has(t)))].map(t => t.replace(/^(PartDesign|Part|Sketcher|App)::/, m => (m === 'PartDesign::' ? 'PD:' : m === 'Sketcher::' ? 'Sk:' : m === 'Part::' ? 'P:' : 'A:')))
  }
  const g = group(name)
  if (g !== cur) { md += `\n## ${g}\n\n| model | covers and expected numbers | feature types | V | ${v1} | ${other ? v2 + ' |' : ''}\n|---|---|---|---|---|${other ? '---|' : ''}\n`; cur = g }
  const cell = head.join(' ').replace(/\|/g, '/').replace(/\s+/g, ' ').trim()
  md += `| ${name} | ${cell} | ${types.join(', ')} | ${hasVar ? 'V' : ''} | ${ok(status[name])} | ${other ? ok(status2?.[name]) + ' |' : ''}\n`
}
const total = models.length
const pass1 = models.filter(f => ok(status[f.slice(0, -3)]) === 'ok').length
const pass2 = status2 ? models.filter(f => ok(status2[f.slice(0, -3)]) === 'ok').length : null
md = md.replace('\n## ', `\nTotals: ${total} models, ${pass1} ok with ${v1}${other ? `, ${pass2} ok with ${v2}` : ''}; ${nvar} models with a parameter variant.\n\n## `)
const extra = path.join(corpus, 'COVERAGE-NOTES.md')
if (fs.existsSync(extra)) md += '\n' + fs.readFileSync(extra, 'utf8')
fs.writeFileSync(path.join(corpus, 'COVERAGE.md'), md)
console.log(`wrote COVERAGE.md: ${total} models, ${pass1} ok${pass2 !== null ? ', ' + pass2 + ' ok (other)' : ''}, ${nvar} variants`)
