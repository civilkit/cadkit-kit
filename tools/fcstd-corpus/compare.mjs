#!/usr/bin/env node
// Compare the dumps of two corpus runs (e.g. two FreeCAD versions).
//   node tools/fcstd-corpus/compare.mjs DIR_A DIR_B [--rel 1e-6] [--md OUT.md]
// Numeric differences above the relative tolerance and every structural difference (missing object/property,
// different string/enum/array length) are listed, grouped by model and by "typeId.property".
import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
const [A, B] = args.filter(a => !a.startsWith('--') && !['1e-6'].includes(a) && fs.existsSync(a) && fs.statSync(a).isDirectory())
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d }
const rel = Number(opt('--rel', '1e-6'))
const mdOut = opt('--md', '')
const load = f => JSON.parse(fs.readFileSync(f, 'utf8'))
const names = fs.readdirSync(A).filter(f => f.endsWith('.dump.json')).sort()

const rows = [] // {model, kind, where, a, b}
function walk(a, b, where, model, ctx) {
  if (typeof a === 'number' && typeof b === 'number') {
    const d = Math.abs(a - b)
    if (d > 1e-9 && d > rel * Math.max(Math.abs(a), Math.abs(b))) rows.push({ model, kind: 'numeric', where, a, b })
    return
  }
  if (a === null || b === null || typeof a !== typeof b || Array.isArray(a) !== Array.isArray(b)) {
    if (JSON.stringify(a) !== JSON.stringify(b)) rows.push({ model, kind: 'structure', where, a: short(a), b: short(b) })
    return
  }
  if (Array.isArray(a)) {
    if (a.length !== b.length) { rows.push({ model, kind: 'structure', where: where + '[length]', a: a.length, b: b.length }); return }
    a.forEach((x, i) => walk(x, b[i], where + '[]', model, ctx))
    return
  }
  if (typeof a === 'object') {
    for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
      if (!(k in a)) rows.push({ model, kind: 'structure', where: where + '.' + k, a: '(absent)', b: short(b[k]) })
      else if (!(k in b)) rows.push({ model, kind: 'structure', where: where + '.' + k, a: short(a[k]), b: '(absent)' })
      else walk(a[k], b[k], where + '.' + k, model, ctx)
    }
    return
  }
  if (a !== b) rows.push({ model, kind: 'structure', where, a: short(a), b: short(b) })
}
const short = v => { const s = JSON.stringify(v); return s && s.length > 70 ? s.slice(0, 70) + '...' : s }

let missing = []
for (const f of names) {
  if (!fs.existsSync(path.join(B, f))) { missing.push(f); continue }
  const a = load(path.join(A, f)), b = load(path.join(B, f))
  const model = f.replace('.dump.json', '')
  delete a.freecad; delete b.freecad
  const oa = Object.fromEntries(a.objects.map(o => [o.name, o])), ob = Object.fromEntries(b.objects.map(o => [o.name, o]))
  for (const n of new Set([...Object.keys(oa), ...Object.keys(ob)])) {
    if (!oa[n]) rows.push({ model, kind: 'structure', where: `object ${n}`, a: '(absent)', b: 'present' })
    else if (!ob[n]) rows.push({ model, kind: 'structure', where: `object ${n}`, a: 'present', b: '(absent)' })
    else walk(oa[n], ob[n], `${oa[n].typeId}`, model)
  }
  for (const k of Object.keys(a)) if (k !== 'objects') walk(a[k], b[k], '$' + k, model)
}

const fa = load(path.join(A, names[0])).freecad, fb = load(path.join(B, names[0].replace(/^.*$/, m => m))).freecad
const groups = new Map()
for (const r of rows) {
  const key = r.kind + ' ' + r.where
  if (!groups.has(key)) groups.set(key, { ...r, models: new Set(), n: 0 })
  const g = groups.get(key); g.models.add(r.model); g.n++
}
let md = `# FreeCAD ${fa.version} vs ${fb.version}: dump differences\n\n`
md += `Generated by tools/fcstd-corpus/compare.mjs (numeric tolerance ${rel} relative, 1e-9 absolute; structural = missing or different non-numeric values).\n`
md += `Compared ${names.length - missing.length} dumps (base and .v1). ${missing.length ? 'Missing in B: ' + missing.join(', ') + '.' : ''}\n\n`
const perModel = new Map()
for (const r of rows) { const p = perModel.get(r.model) ?? { numeric: 0, structure: 0 }; p[r.kind]++; perModel.set(r.model, p) }
md += `Total: ${rows.filter(r => r.kind === 'numeric').length} numeric and ${rows.filter(r => r.kind === 'structure').length} structural differences in ${perModel.size} of ${names.length} dumps, ${groups.size} distinct kinds.\n\n`
if (groups.size) {
  md += '## By kind\n\n| kind | typeId.property | count | dumps | example (A -> B) |\n|---|---|---|---|---|\n'
  for (const g of [...groups.values()].sort((x, y) => y.n - x.n)) {
    md += `| ${g.kind} | \`${g.where.replace(/\|/g, '/')}\` | ${g.n} | ${g.models.size} (${[...g.models].slice(0, 2).join(', ')}${g.models.size > 2 ? ', ...' : ''}) | ${g.a} -> ${g.b} |\n`
  }
  md += '\n## By dump\n\n| dump | numeric | structural |\n|---|---|---|\n'
  for (const [m, p] of [...perModel].sort()) md += `| ${m} | ${p.numeric} | ${p.structure} |\n`
} else md += 'No differences.\n'
if (mdOut) fs.writeFileSync(mdOut, md)
else console.log(md)
console.error(`${rows.length} differences`)
