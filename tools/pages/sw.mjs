// The service worker of the published site: makes the app installable and lets it start offline after the first visit.
// Written at build time (tools/build_pages.mjs) because it lists the exact files of that build.
//   - install: stores the app shell (index.html, the hashed bundles, the kernel wasm, icons, manifest) in a cache named after the build
//   - activate: drops the caches of older builds
//   - a phone or tablet registers it as sw.js?lite: the ~7 MB kernel wasm is then not stored at install (it would compete with the first
//     load on a mobile connection and fill a small quota) but cached by the fetch handler the first time the app asks for it
//   - fetch: the hashed assets/ files never change, so they come from the cache first; everything else (index.html, the kernel,
//     samples) tries the network first and falls back to the stored copy, so a deploy is picked up on the next load
import { createHash } from 'node:crypto';

/** A short id of this build: the file names with their sizes. */
export function buildId(files) {
  const h = createHash('sha256');
  for (const f of [...files].sort((a, b) => a.path.localeCompare(b.path))) h.update(`${f.path}:${f.size}\n`);
  return h.digest('hex').slice(0, 12);
}

/** Files a lite install (phone, tablet) leaves out of the precache; the fetch handler stores them when they are first requested. */
export const LITE_SKIP = 'kernel/';

/** The files to store at install: the shell, not the samples (those are fetched when used). */
export function precacheList(paths) {
  return paths.filter((p) => p === 'index.html' || p === 'manifest.webmanifest' || p.startsWith('assets/') || p.startsWith('kernel/') || p.startsWith('icons/')).sort();
}

export function swSource(id, precache) {
  return `// generated by tools/build_pages.mjs, do not edit
const BUILD = ${JSON.stringify(id)};
const CACHE = 'cadkit-' + BUILD;
const scope = self.registration.scope;
// registered as sw.js?lite by a phone or tablet: the kernel is cached on first use instead of at install
const LITE = new URL(self.location.href).searchParams.has('lite');
const PRECACHE = ${JSON.stringify(precache)}.filter((p) => !(LITE && p.startsWith(${JSON.stringify(LITE_SKIP)})));

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll([scope, ...PRECACHE.map((p) => new URL(p, scope).href)])).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('cadkit-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

const networkFirst = async (req) => {
  try {
    const res = await fetch(req);
    if (res.ok && res.status === 200) { const c = await caches.open(CACHE); c.put(req, res.clone()).catch(() => {}); }
    return res;
  } catch (err) {
    const hit = await caches.match(req, { ignoreSearch: true });
    if (hit) return hit;
    if (req.mode === 'navigate') { const shell = await caches.match(scope); if (shell) return shell; }
    throw err;
  }
};

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin || req.headers.has('range')) return;
  if (new URL(req.url).pathname.includes('/assets/')) {
    e.respondWith(caches.match(req).then((hit) => hit || networkFirst(req)));
  } else e.respondWith(networkFirst(req));
});
`;
}
